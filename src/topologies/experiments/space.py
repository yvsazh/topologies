"""Axes, labels, ``Variant``, distributions and trial-point generation.

An *axis* is one thing that varies (``"model"``, ``"tokenizer"``,
``"lr"`` ...). Its values are normalized into ``AxisValue(label, value,
overrides)``:

    axes = {
        "model": [TransformerLM, Variant("llama-ish", TransformerLM, pos="rope")],
        "tokenizer": ["char", "bpe:4k"],
        "lr": loguniform(1e-4, 1e-2),          # space="random" only (or .grid(5))
    }

Points are generated by ``grid_points`` (Cartesian product),
``random_points`` (deterministic sampling) or ``ofat_points`` (baseline +
one change at a time), then filtered (``where`` / ``exclude``) and extended
(``include``). ``trial_order`` interleaves seeds: seed 0 of every config
first (deterministically shuffled), then seed 1, ...
"""

from __future__ import annotations

import hashlib
import itertools
import math
import random
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from typing import Any

from topologies.experiments.distributions import (  # re-exported
    Distribution,
    choice,
    intloguniform,
    intuniform,
    loguniform,
    uniform,
)
from topologies.experiments.errors import ExperimentError

#: Keys that a ``Variant`` override always treats as absolute (never namespaced).
ABSOLUTE_KEYS = frozenset({"model", "size", "target_params", "search", "tolerance",
                           "param_count", "tokenizer", "optimizer", "scheduler", "loss",
                           "recipe", "train_for", "seed"})
#: Axes whose bare ``Variant`` overrides live in the axis namespace (``model.pos``).
NAMESPACED_AXES = frozenset({"model", "tokenizer", "optimizer", "scheduler", "loss", "recipe"})

_UNSET: Any = object()


# ---------------------------------------------------------------- labelled values


class Variant:
    """A labelled axis value that also changes other keys ("coupled overrides").

    >>> Variant("llama-ish", TransformerLM, pos="rope", norm="rms",
    ...         **{"trainer.lr": 3e-4})

    Bare override keys resolve inside the axis namespace (constructor kwargs
    on the ``model`` axis, tokenizer kwargs on ``tokenizer``); dotted keys are
    absolute. ``search={...}`` / ``target_params=None`` / ``size=...`` tune
    how the model is built. ``value=None`` makes a pure label (a "virtual"
    axis whose values only carry overrides).
    """

    __slots__ = ("label", "overrides", "value")

    def __init__(self, label: str, value: Any = None, **overrides: Any) -> None:
        if not isinstance(label, str) or not label:
            raise ExperimentError("Variant label must be a non-empty string.", stage="space",
                                  hint='Variant("rope", TransformerLM, pos="rope")')
        self.label = label
        self.value = value
        self.overrides = dict(overrides)

    def __repr__(self) -> str:
        extra = "".join(f", {k}={v!r}" for k, v in self.overrides.items())
        return f"Variant({self.label!r}, {self.value!r}{extra})"


class Fixed:
    """Wraps a (list-valued) constant so ``compare()`` does not turn it into an axis."""

    __slots__ = ("value",)

    def __init__(self, value: Any) -> None:
        self.value = value

    def __repr__(self) -> str:
        return f"fixed({self.value!r})"


def fixed(value: Any) -> Fixed:
    """``compare(..., betas=fixed([0.9, 0.95]))``: a list that is a setting, not an axis."""
    return Fixed(value)


# ---------------------------------------------------------------- labels


def compact_number(x: Any) -> str:
    """``3e-4`` -> ``"3e-4"``, ``0.001`` -> ``"1e-3"``, ``0.5`` -> ``"0.5"``, ``128`` -> ``"128"``."""
    if isinstance(x, bool) or not isinstance(x, (int, float)):
        return str(x)
    if isinstance(x, int):
        return str(x)
    if math.isnan(x) or math.isinf(x):
        return str(x)
    a = abs(x)
    if a != 0 and (a < 0.01 or a >= 1e5):
        mant, _, exp = f"{x:.3g}".partition("e")
        if not exp:
            mant, _, exp = f"{x:.2e}".partition("e")
        mant = mant.rstrip("0").rstrip(".") if "." in mant else mant
        return f"{mant}e{int(exp)}"
    text = f"{x:.6g}"
    return text if ("." in text or "e" in text) else f"{text}.0"


def _short_k(n: int) -> str:
    return f"{n // 1024}k" if n >= 1024 and n % 1024 == 0 else str(n)


def tokenizer_label(spec: Any) -> str | None:
    """Normalized tokenizer spec label (``"bpe:4k"``) or ``None`` if not a spec."""
    from topologies.experiments.routing import parse_tokenizer_spec

    try:
        d = parse_tokenizer_spec(spec)
    except Exception:  # noqa: BLE001
        return None
    if d is None:
        return None
    kind = d.get("kind", "?")
    if kind == "hf":
        kind = f"hf-{d.get('model', 'bpe')}"
    vs = d.get("vocab_size")
    extra = {k: v for k, v in d.items() if k not in ("kind", "vocab_size", "model")}
    base = kind if vs is None else f"{kind}:{_short_k(int(vs))}"
    if extra:
        base += "," + ",".join(f"{k}={_value_label(v)}" for k, v in sorted(extra.items()))
    return base


def _value_label(v: Any) -> str:
    if isinstance(v, float):
        return compact_number(v)
    if isinstance(v, type):
        return v.__name__
    if callable(v) and hasattr(v, "__name__"):
        return str(v.__name__)
    if isinstance(v, (list, tuple)):
        return "[" + ",".join(_value_label(x) for x in v) + "]"
    return str(v)


def label_for(axis: str, value: Any) -> str:
    """Automatic label of an axis value (see module docstring of ``space``)."""
    if value is None:
        return "none"
    if axis == "tokenizer" or axis.startswith("tokenizer"):
        if hasattr(value, "encode") and hasattr(value, "vocab_size"):
            kind = getattr(value, "kind", type(value).__name__)
            try:
                return f"{kind}:{_short_k(int(value.vocab_size))}"
            except Exception:  # noqa: BLE001
                return str(kind)
        if isinstance(value, (str, dict)):
            lab = tokenizer_label(value)
            if lab is not None:
                return lab
    if isinstance(value, type):
        return value.__name__
    if isinstance(value, str):
        if ":" in value and "/" not in value and " " not in value:
            return value.rsplit(":", 1)[-1].rsplit(".", 1)[-1] or value
        return value
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, (int, float)):
        return compact_number(value)
    if isinstance(value, dict):
        return ",".join(f"{k}={_value_label(v)}" for k, v in value.items()) or "{}"
    if callable(value):
        name = getattr(value, "__name__", None) or type(value).__name__
        return str(name)
    if isinstance(value, (list, tuple)):
        return _value_label(value)
    text = str(value)
    return text if len(text) <= 40 else text[:37] + "..."


# ---------------------------------------------------------------- normalized axes


@dataclass
class AxisValue:
    """One labelled value of an axis (plus coupled overrides by absolute key)."""

    label: str
    value: Any = None
    overrides: dict[str, Any] = field(default_factory=dict)
    has_value: bool = True

    def assignments(self, axis: str) -> dict[str, Any]:
        """Keys this value sets: the axis itself (when it carries a value) + overrides."""
        out: dict[str, Any] = {}
        if self.has_value:
            out[axis] = self.value
        out.update(self.overrides)
        return out


@dataclass
class Axis:
    name: str
    values: list[AxisValue]
    distribution: Distribution | None = None

    @property
    def labels(self) -> list[str]:
        return [v.label for v in self.values]

    @property
    def virtual(self) -> bool:
        """All values are pure ``Variant`` labels (the axis key itself is never set)."""
        return bool(self.values) and not any(v.has_value for v in self.values)

    def find(self, x: Any) -> AxisValue | None:
        """Value matching a label or a raw value."""
        for v in self.values:
            if isinstance(x, str) and v.label == x:
                return v
        for v in self.values:
            try:
                if v.has_value and (v.value is x or bool(v.value == x)):
                    return v
            except Exception:  # noqa: BLE001, S112 - user values may not support ==
                continue
        return None


def _namespace_overrides(axis: str, overrides: dict[str, Any], free_form: bool) -> dict:
    out: dict[str, Any] = {}
    for k, v in overrides.items():
        if free_form or "." in k or k in ABSOLUTE_KEYS:
            out[k] = v
        elif axis in NAMESPACED_AXES:
            out[f"{axis}.{k}"] = v
        else:
            out[k] = v
    return out


def _axis_value(axis: str, label: str | None, raw: Any, free_form: bool) -> AxisValue:
    if isinstance(raw, Variant):
        return AxisValue(label=raw.label if label is None else label, value=raw.value,
                         overrides=_namespace_overrides(axis, raw.overrides, free_form),
                         has_value=raw.value is not None)
    if isinstance(raw, Fixed):
        raw = raw.value
    return AxisValue(label=label_for(axis, raw) if label is None else str(label), value=raw)


def _dedupe_labels(values: list[AxisValue]) -> None:
    seen: dict[str, int] = {}
    for v in values:
        n = seen.get(v.label, 0) + 1
        seen[v.label] = n
        if n > 1:
            v.label = f"{v.label}#{n}"


def normalize_axis(name: str, spec: Any, *, free_form: bool = False) -> Axis:
    """List / ``{label: value}`` dict / distribution -> ``Axis``."""
    if not isinstance(name, str) or not name:
        raise ExperimentError(f"Axis names must be non-empty strings; got {name!r}.",
                              stage="space")
    if isinstance(spec, Distribution):
        if isinstance(spec, choice):
            values = [_axis_value(name, None, v, free_form) for v in spec.values]
            _dedupe_labels(values)
            return Axis(name, values, spec)
        return Axis(name, [], spec)
    if isinstance(spec, dict):
        if not spec:
            raise ExperimentError(f"Axis {name!r} has no values.", stage="space")
        values = [_axis_value(name, str(k), v, free_form) for k, v in spec.items()]
    elif isinstance(spec, (list, tuple, range)):
        if not len(spec):
            raise ExperimentError(f"Axis {name!r} has no values.", stage="space")
        values = [_axis_value(name, None, v, free_form) for v in spec]
    else:
        raise ExperimentError(
            f"Axis {name!r} must be a list, a {{label: value}} dict or a distribution; "
            f"got {type(spec).__name__}.",
            stage="space", key=name,
            hint=f"Use axes={{{name!r}: [a, b]}}, or move a constant to fixed={{{name!r}: ...}}.",
        )
    _dedupe_labels(values)
    return Axis(name, values)


def normalize_axes(axes: dict[str, Any] | None, *, free_form: bool = False) -> list[Axis]:
    return [normalize_axis(k, v, free_form=free_form) for k, v in (axes or {}).items()]


# ---------------------------------------------------------------- seeds / points

Point = dict[str, AxisValue]


def resolve_seeds(seeds: int | Sequence[int]) -> list[int]:
    if isinstance(seeds, bool):
        raise ExperimentError("seeds must be an int (count) or a list of seeds.", stage="space")
    if isinstance(seeds, int):
        if seeds < 1:
            raise ExperimentError(f"seeds must be >= 1; got {seeds}.", stage="space")
        return list(range(seeds))
    out = [int(s) for s in seeds]
    if not out:
        raise ExperimentError("seeds list is empty.", stage="space")
    if len(set(out)) != len(out):
        raise ExperimentError(f"duplicate seeds in {out}.", stage="space")
    return out


def labels_of(point: Point) -> dict[str, str]:
    return {k: v.label for k, v in point.items()}


def point_key(point: Point) -> tuple:
    return tuple(sorted(labels_of(point).items()))


def grid_points(axes: list[Axis]) -> list[Point]:
    for ax in axes:
        if ax.distribution is not None and not isinstance(ax.distribution, choice):
            raise ExperimentError(
                f"Axis {ax.name!r} is a distribution ({ax.distribution.describe()}); a grid "
                "needs discrete values.",
                stage="space", key=ax.name,
                hint=f"Use space='random' (with n_trials=...), or discretize: "
                     f"{ax.distribution.describe()}.grid(5).",
            )
    if not axes:
        return [{}]
    return [dict(zip([a.name for a in axes], combo))
            for combo in itertools.product(*(a.values for a in axes))]


def _rng(name: str, base: int = 0) -> random.Random:
    digest = hashlib.sha256(f"{name}|{base}".encode()).hexdigest()
    return random.Random(int(digest[:16], 16))


def random_points(axes: list[Axis], n: int, *, name: str, seed_base: int = 0) -> list[Point]:
    """``n`` deterministic samples; a larger ``n`` extends the same sequence."""
    if n is None or n < 1:
        raise ExperimentError("space='random' needs n_trials >= 1.", stage="space",
                              hint="Experiment(..., space='random', n_trials=20)")
    rng = _rng(name, seed_base)
    out: list[Point] = []
    seen: set[tuple] = set()
    attempts = 0
    while len(out) < n and attempts < n * 50:
        attempts += 1
        point: Point = {}
        for ax in axes:
            if ax.distribution is not None and not isinstance(ax.distribution, choice):
                v = ax.distribution.sample(rng)
                point[ax.name] = AxisValue(label=label_for(ax.name, v), value=v)
            else:
                point[ax.name] = ax.values[rng.randrange(len(ax.values))]
        key = point_key(point)
        if key in seen:
            continue  # duplicates waste compute; keep sampling (the sequence stays fixed)
        seen.add(key)
        out.append(point)
    return out


def _matches(av: AxisValue, want: Any) -> bool:
    if isinstance(want, (list, tuple, set, frozenset)) and not isinstance(want, str):
        return any(_matches(av, w) for w in want)
    if isinstance(want, str) and av.label == want:
        return True
    try:
        return av.has_value and (av.value is want or bool(av.value == want))
    except Exception:  # noqa: BLE001
        return False


def point_matches(point: Point, spec: dict[str, Any]) -> bool:
    """True when every ``axis: label|value|[...]`` of ``spec`` matches ``point``."""
    for k, want in spec.items():
        if k not in point or not _matches(point[k], want):
            return False
    return True


def ofat_points(axes: list[Axis], baseline: dict[str, Any] | None) -> list[Point]:
    """One factor at a time: the baseline point, then each single-axis change."""
    if not baseline:
        raise ExperimentError(
            "space='ofat' needs baseline={axis: value, ...} (the ablation centre).",
            stage="space", hint="Experiment(..., space='ofat', baseline={'model.pos': 'rope'})")
    grid_points(axes)  # validates discreteness
    base: Point = {}
    for ax in axes:
        if ax.name not in baseline:
            raise ExperimentError(f"baseline has no value for axis {ax.name!r}.", stage="space",
                                  key=ax.name, available=ax.labels)
        av = ax.find(baseline[ax.name])
        if av is None:
            raise ExperimentError(
                f"baseline value {baseline[ax.name]!r} is not one of axis {ax.name!r}'s values.",
                stage="space", key=ax.name, available=ax.labels,
                hint="Every axis must contain the baseline value.")
        base[ax.name] = av
    unknown = [k for k in baseline if k not in {a.name for a in axes}]
    if unknown:
        raise ExperimentError(f"baseline names unknown axes {unknown}.", stage="space",
                              available=[a.name for a in axes])
    out = [dict(base)]
    for ax in axes:
        for av in ax.values:
            if av is base[ax.name]:
                continue
            p = dict(base)
            p[ax.name] = av
            out.append(p)
    return out


def apply_filters(points: list[Point], axes: list[Axis], *,
                  where: Callable[[dict], bool] | None = None,
                  exclude: list[dict] | None = None,
                  include: list[dict] | None = None,
                  baseline: dict[str, Any] | None = None) -> list[Point]:
    """``where(labels)`` / ``exclude`` drop points; ``include`` adds explicit ones."""
    out = []
    for p in points:
        if where is not None:
            try:
                keep = bool(where(labels_of(p)))
            except Exception as e:
                raise ExperimentError(f"where() failed on {labels_of(p)}: {e}",
                                      stage="space") from e
            if not keep:
                continue
        if exclude and any(point_matches(p, ex) for ex in exclude):
            continue
        out.append(p)
    by_name = {a.name: a for a in axes}
    for inc in include or []:
        if not isinstance(inc, dict):
            raise ExperimentError("include entries must be dicts {axis: label_or_value}.",
                                  stage="space")
        unknown = [k for k in inc if k not in by_name]
        if unknown:
            raise ExperimentError(f"include names unknown axes {unknown}.", stage="space",
                                  available=list(by_name))
        p: Point = {}
        for name, ax in by_name.items():
            if name in inc:
                av = ax.find(inc[name])
                if av is None:
                    v = inc[name]
                    v = v.value if isinstance(v, Fixed) else v
                    av = _axis_value(name, None, v, False)
                p[name] = av
            elif baseline and name in baseline and ax.find(baseline[name]) is not None:
                p[name] = ax.find(baseline[name])  # type: ignore[assignment]
            else:
                raise ExperimentError(
                    f"include entry {inc} has no value for axis {name!r}.", stage="space",
                    key=name, hint="Give every axis a value (or set baseline=... to fill gaps).")
        if point_key(p) not in {point_key(q) for q in out}:
            out.append(p)
    return out


def trial_order(points: list[Point], seeds: list[int], *, name: str) -> list[tuple[Point, int]]:
    """Interleaved: every config with seed 0 (shuffled deterministically), then seed 1, ..."""
    order = list(range(len(points)))
    _rng(name, 7919).shuffle(order)
    return [(points[i], s) for s in seeds for i in order]


